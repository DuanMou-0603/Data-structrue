def factorial(n):
    """递归计算阶乘

    递归方法论分析：
    1. 找出基线条件：当 n == 0 或 n == 1 时，阶乘为 1，直接返回
    2. 用显式栈保存状态：系统调用栈会保存每次递归调用的 n 值和返回地址
    3. 初始状态入栈：第一次调用 factorial(n) 时，将 n 和返回地址压入栈
    4. 循环出栈执行：系统自动处理栈的出栈和执行，直到栈为空
    """
    print(f"计算 {n} 的阶乘")
    # 1. 基线条件：当 n 为 0 或 1 时，阶乘为 1，直接返回
    if n == 0 or n == 1:
        return 1
    else:
        # 递归调用：将 n-1 和返回地址压入栈，然后执行 factorial(n-1)
        # 当 factorial(n-1) 执行完成后，栈顶元素出栈，继续执行乘法操作
        return n * factorial(n - 1)

def factorial_iterative(n):
    """迭代计算阶乘

    迭代方法论分析：
    1. 找出基线条件：当 n == 0 或 n == 1 时，阶乘为 1，直接返回
    2. 用显式栈保存状态：使用变量 result 来保存中间计算结果，模拟栈的功能
    3. 初始状态入栈：初始化 result = 1，相当于将初始状态压入栈
    4. 循环出栈执行：通过 for 循环遍历，依次执行乘法操作，直到循环结束
    """
    print(f"计算 {n} 的阶乘")
    # 1. 基线条件：当 n 为 0 或 1 时，阶乘为 1，直接返回
    if n == 0 or n == 1:
        return 1
    else:
        # 2. 用显式栈保存状态：使用 result 变量保存中间结果
        result = 1
        # 4. 循环出栈执行：通过 for 循环模拟递归的迭代过程
        for i in range(2, n + 1):
            result *= i
        return result

